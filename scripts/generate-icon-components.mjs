#!/usr/bin/env node
/**
 * ARQ-020: create icon package.
 *
 * Generates packages/icons/src/generated/*.tsx from design/icons/svg/*.svg (the 40
 * draft icons already reviewed under ARQ-021ish/design work) - each source SVG
 * already uses stroke="currentColor" (themable by CSS `color`, verified by reading
 * the source files directly, not assumed), so the generated component only needs to
 * carry the viewBox and inner markup through, spreading standard SVG props.
 *
 * Regenerate after any change to design/icons/svg/*.svg:
 *   node scripts/generate-icon-components.mjs
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');
const svgDir = path.join(repoRoot, 'design/icons/svg');
const outDir = path.join(repoRoot, 'packages/icons/src/generated');

function toPascalCase(kebab) {
  return kebab
    .split('-')
    .map((part) => (/^\d/.test(part) ? part : part.charAt(0).toUpperCase() + part.slice(1)))
    .join('');
}

function extractViewBoxAndInner(svgSource) {
  const viewBoxMatch = svgSource.match(/viewBox="([^"]+)"/);
  const innerMatch = svgSource.match(/<svg[^>]*>([\s\S]*)<\/svg>/);
  if (!viewBoxMatch || !innerMatch) {
    throw new Error('could not parse viewBox/inner content from SVG source');
  }
  return { viewBox: viewBoxMatch[1], inner: innerMatch[1].trim() };
}

mkdirSync(outDir, { recursive: true });

const files = readdirSync(svgDir)
  .filter((name) => name.endsWith('.svg'))
  .sort();

const exports = [];

for (const file of files) {
  const baseName = file.replace(/\.svg$/, '');
  const componentName = `${toPascalCase(baseName)}Icon`;
  const source = readFileSync(path.join(svgDir, file), 'utf8');
  const { viewBox, inner } = extractViewBoxAndInner(source);

  const tsx = `// Generated by scripts/generate-icon-components.mjs from design/icons/svg/${file} - do not edit directly.
import type { SVGProps } from 'react';

export function ${componentName}(props: SVGProps<SVGSVGElement>): JSX.Element {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="${viewBox}"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      width="1em"
      height="1em"
      aria-hidden="true"
      focusable="false"
      {...props}
    >
      ${inner}
    </svg>
  );
}
`;
  writeFileSync(path.join(outDir, `${componentName}.tsx`), tsx);
  exports.push({ baseName, componentName });
}

const indexContent = [
  '// Generated by scripts/generate-icon-components.mjs - do not edit directly.',
  ...exports.map((e) => `export { ${e.componentName} } from './${e.componentName}';`),
  '',
].join('\n');
writeFileSync(path.join(outDir, 'index.ts'), indexContent);

console.log(`Generated ${exports.length} icon components in ${path.relative(repoRoot, outDir)}/`);
